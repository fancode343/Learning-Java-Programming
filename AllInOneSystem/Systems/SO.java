package AllInOneSystem.Systems;

public class SO {
    public static void P(Object ob) {
        System.out.print(ob);
    }

    public static void Pln(Object ob) {
        System.out.println(ob);
    }

    public static void Pln() {
        System.out.println();
    }

    public static String getName() {
        return "SOP Shortcut";
    }
}
